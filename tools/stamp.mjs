// Stamps version.json (and the release public key) into the places the build reads:
//   companion/Directory.Build.props   -> assembly versions
//   companion/Toolize.Service/ReleaseKey.cs -> repo + release public key
// The extension manifest is stamped by extension/build.mjs.
//
//   node tools/stamp.mjs            stamp the current version
//   node tools/stamp.mjs 0.4.0      set a new version first
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensureKeys, releasePublicKeyBase64 } from './keys.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const versionFile = join(root, 'version.json');

export function stamp(newVersion) {
  ensureKeys({ quiet: true });
  const meta = JSON.parse(readFileSync(versionFile, 'utf8'));
  if (newVersion) {
    if (!/^\d+\.\d+\.\d+$/.test(newVersion)) throw new Error(`version must be x.y.z, got "${newVersion}"`);
    meta.version = newVersion;
    writeFileSync(versionFile, JSON.stringify(meta, null, 2) + '\n');
  }

  writeFileSync(
    join(root, 'companion/Directory.Build.props'),
    `<!-- Generated by tools/stamp.mjs from version.json. Do not edit. -->
<Project>
  <PropertyGroup>
    <Version>${meta.version}</Version>
    <Company>Toolize</Company>
    <Product>Toolize</Product>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
  </PropertyGroup>
</Project>
`,
  );

  writeFileSync(
    join(root, 'companion/Toolize.Service/ReleaseKey.cs'),
    `// Generated by tools/stamp.mjs. Do not edit.
//
// The public half of the release signing key. An update is only installed if its
// manifest carries a signature that verifies against this — so whoever holds the
// private half (and only them) can push code to installed machines.
namespace Toolize.Service;

internal static class ReleaseKey
{
    public const string Repo = "${meta.repo}";
    public const string PublicKeyBase64 =
        "${releasePublicKeyBase64()}";
}
`,
  );

  return meta;
}

if (process.argv[1]?.endsWith('stamp.mjs')) {
  const meta = stamp(process.argv[2]);
  console.log(`stamped version ${meta.version} (repo ${meta.repo})`);
}
